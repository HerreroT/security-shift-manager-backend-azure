-- Initial schema. Written to run both on PostgreSQL and on H2 in PostgreSQL mode.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(255) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    active        BOOLEAN      NOT NULL,
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE guards (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(255) NOT NULL,
    last_name  VARCHAR(255) NOT NULL,
    dni        VARCHAR(255) NOT NULL,
    phone      VARCHAR(255) NOT NULL,
    active     BOOLEAN      NOT NULL,
    CONSTRAINT uk_guards_dni UNIQUE (dni)
);

CREATE TABLE services (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    location    VARCHAR(255) NOT NULL,
    description VARCHAR(500),
    active      BOOLEAN      NOT NULL
);

CREATE TABLE shift_assignments (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guard_id          BIGINT        NOT NULL,
    service_id        BIGINT        NOT NULL,
    start_date_time   TIMESTAMP(6)  NOT NULL,
    end_date_time     TIMESTAMP(6)  NOT NULL,
    total_hours       NUMERIC(5, 2) NOT NULL,
    notes             VARCHAR(500),
    actual_start_time TIMESTAMP(6),
    actual_end_time   TIMESTAMP(6),
    CONSTRAINT fk_shift_guard FOREIGN KEY (guard_id) REFERENCES guards (id),
    CONSTRAINT fk_shift_service FOREIGN KEY (service_id) REFERENCES services (id),
    CONSTRAINT chk_shift_end_after_start CHECK (end_date_time > start_date_time)
);

CREATE INDEX idx_shift_guard_start ON shift_assignments (guard_id, start_date_time);
CREATE INDEX idx_shift_service_start ON shift_assignments (service_id, start_date_time);
